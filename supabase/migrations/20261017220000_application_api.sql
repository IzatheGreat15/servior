CREATE OR REPLACE FUNCTION public.get_staff_branch(p_branch_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_result jsonb;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.branches b
    WHERE b.id = p_branch_id
      AND public.is_tenant_employee(b.tenant_id)
  ) THEN
    RAISE EXCEPTION 'Branch not found or access denied.'
      USING ERRCODE = '42501';
  END IF;

  SELECT jsonb_build_object(
    'id', b.id::text,
    'name', b.branch_name,
    'address', COALESCE(b.address, b.branch_location ->> 'address', ''),
    'phone', COALESCE(b.contact_number, ''),
    'email', COALESCE(b.email, ''),
    'openingTime', COALESCE(to_char(b.opening_time, 'HH24:MI'), '06:00'),
    'closingTime', COALESCE(to_char(b.closing_time, 'HH24:MI'), '22:00'),
    'sports', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', grouped.sport_id::text,
        'name', grouped.sport_name,
        'courts', grouped.courts
      ) ORDER BY grouped.sport_name)
      FROM (
        SELECT s.id AS sport_id, s.sport_name,
          jsonb_agg(jsonb_build_object(
            'id', c.id::text,
            'name', c.court_name,
            'active', c.is_active,
            'photoUrl', c.court_image,
            'rules', COALESCE((
              SELECT jsonb_agg(jsonb_build_object(
                'id', r.id::text,
                'days', to_jsonb(r.days),
                'startTime', to_char(r.start_time, 'HH24:MI'),
                'endTime', to_char(r.end_time, 'HH24:MI'),
                'hourlyRate', r.hourly_rate
              ) ORDER BY r.start_time)
              FROM public.court_pricing_rules r
              WHERE r.court_id = c.id
            ), '[]'::jsonb)
          ) ORDER BY c.court_name)
          AS courts
        FROM public.courts c
        JOIN public.sports s ON s.id = c.sport_id
        WHERE c.branch_id = b.id
        GROUP BY s.id, s.sport_name
      ) grouped
    ), '[]'::jsonb)
  )
  INTO v_result
  FROM public.branches b
  WHERE b.id = p_branch_id;

  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.save_staff_branch(
  p_branch_id bigint,
  p_branch jsonb,
  p_sports jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_tenant_id bigint;
  v_branch_id bigint := p_branch_id;
  v_sport jsonb;
  v_court jsonb;
  v_rule jsonb;
  v_sport_id bigint;
  v_court_id bigint;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Authentication required.' USING ERRCODE = '42501';
  END IF;

  SELECT e.tenant_id INTO v_tenant_id
  FROM public.employees e
  WHERE e.user_id = auth.uid()
  ORDER BY e.tenant_id
  LIMIT 1;

  IF v_tenant_id IS NULL THEN
    RAISE EXCEPTION 'Staff membership required.' USING ERRCODE = '42501';
  END IF;

  IF jsonb_typeof(p_branch) <> 'object'
     OR jsonb_typeof(p_sports) <> 'array'
     OR length(btrim(COALESCE(p_branch ->> 'name', ''))) NOT BETWEEN 1 AND 150
     OR length(btrim(COALESCE(p_branch ->> 'address', ''))) NOT BETWEEN 1 AND 500 THEN
    RAISE EXCEPTION 'Branch details are invalid.' USING ERRCODE = '22023';
  END IF;

  IF p_branch_id IS NULL THEN
    INSERT INTO public.branches (
      tenant_id, branch_name, branch_location, location, address,
      contact_number, email, opening_time, closing_time
    )
    VALUES (
      v_tenant_id,
      btrim(p_branch ->> 'name'),
      json_build_object('address', btrim(p_branch ->> 'address')),
      jsonb_build_object('address', btrim(p_branch ->> 'address')),
      btrim(p_branch ->> 'address'),
      NULLIF(btrim(p_branch ->> 'phone'), ''),
      NULLIF(lower(btrim(p_branch ->> 'email')), ''),
      COALESCE(NULLIF(p_branch ->> 'openingTime', ''), '06:00')::time,
      COALESCE(NULLIF(p_branch ->> 'closingTime', ''), '22:00')::time
    )
    RETURNING id INTO v_branch_id;
  ELSE
    UPDATE public.branches
    SET branch_name = btrim(p_branch ->> 'name'),
        branch_location = json_build_object('address', btrim(p_branch ->> 'address')),
        location = jsonb_build_object('address', btrim(p_branch ->> 'address')),
        address = btrim(p_branch ->> 'address'),
        contact_number = NULLIF(btrim(p_branch ->> 'phone'), ''),
        email = NULLIF(lower(btrim(p_branch ->> 'email')), ''),
        opening_time = COALESCE(NULLIF(p_branch ->> 'openingTime', ''), '06:00')::time,
        closing_time = COALESCE(NULLIF(p_branch ->> 'closingTime', ''), '22:00')::time,
        updated_at = now()
    WHERE id = p_branch_id
      AND tenant_id = v_tenant_id;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Branch not found or access denied.'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  FOR v_sport IN SELECT value FROM jsonb_array_elements(p_sports)
  LOOP
    IF length(btrim(COALESCE(v_sport ->> 'name', ''))) NOT BETWEEN 1 AND 100
       OR jsonb_typeof(v_sport -> 'courts') <> 'array' THEN
      RAISE EXCEPTION 'Sport or court details are invalid.'
        USING ERRCODE = '22023';
    END IF;

    SELECT id INTO v_sport_id
    FROM public.sports
    WHERE lower(sport_name) = lower(btrim(v_sport ->> 'name'))
    ORDER BY id
    LIMIT 1;

    IF v_sport_id IS NULL THEN
      INSERT INTO public.sports (sport_name)
      VALUES (btrim(v_sport ->> 'name'))
      RETURNING id INTO v_sport_id;
    END IF;

    FOR v_court IN SELECT value FROM jsonb_array_elements(v_sport -> 'courts')
    LOOP
      IF length(btrim(COALESCE(v_court ->> 'name', ''))) NOT BETWEEN 1 AND 150
         OR jsonb_typeof(v_court -> 'rules') <> 'array' THEN
        RAISE EXCEPTION 'Court details are invalid.' USING ERRCODE = '22023';
      END IF;

      IF NULLIF(v_court ->> 'id', '') IS NOT NULL
         AND (v_court ->> 'id') ~ '^[1-9][0-9]*$' THEN
        UPDATE public.courts
        SET court_name = btrim(v_court ->> 'name'),
            is_active = COALESCE((v_court ->> 'active')::boolean, true),
            court_image = NULLIF(v_court ->> 'photoUrl', ''),
            branch_id = v_branch_id,
            sport_id = v_sport_id,
            updated_st = now()
        WHERE id = (v_court ->> 'id')::bigint
          AND branch_id = v_branch_id;
        IF NOT FOUND THEN
          RAISE EXCEPTION 'Court not found or access denied.'
            USING ERRCODE = '42501';
        END IF;
        v_court_id := (v_court ->> 'id')::bigint;
      ELSE
        INSERT INTO public.courts (
          branch_id, sport_id, court_name, price, is_active, court_image,
          opening_time, closing_time
        )
        VALUES (
          v_branch_id, v_sport_id, btrim(v_court ->> 'name'), 0,
          COALESCE((v_court ->> 'active')::boolean, true),
          NULLIF(v_court ->> 'photoUrl', ''),
          (p_branch ->> 'openingTime')::time,
          (p_branch ->> 'closingTime')::time
        )
        RETURNING id INTO v_court_id;
      END IF;

      DELETE FROM public.court_pricing_rules WHERE court_id = v_court_id;
      FOR v_rule IN SELECT value FROM jsonb_array_elements(v_court -> 'rules')
      LOOP
        IF jsonb_typeof(v_rule -> 'days') <> 'array'
           OR length(COALESCE(v_rule ->> 'startTime', '')) <> 5
           OR length(COALESCE(v_rule ->> 'endTime', '')) <> 5
           OR COALESCE((v_rule ->> 'hourlyRate')::numeric, -1) < 0 THEN
          RAISE EXCEPTION 'Pricing rule is invalid.' USING ERRCODE = '22023';
        END IF;

        INSERT INTO public.court_pricing_rules (
          court_id, days, start_time, end_time, hourly_rate
        )
        SELECT v_court_id,
          ARRAY(SELECT jsonb_array_elements_text(v_rule -> 'days')),
          (v_rule ->> 'startTime')::time,
          (v_rule ->> 'endTime')::time,
          (v_rule ->> 'hourlyRate')::numeric;
      END LOOP;
    END LOOP;
  END LOOP;

  RETURN public.get_staff_branch(v_branch_id);
END;
$$;

REVOKE ALL ON FUNCTION public.get_staff_branch(bigint) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.save_staff_branch(bigint, jsonb, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_staff_branch(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.save_staff_branch(bigint, jsonb, jsonb) TO authenticated;

